def parse_diff(diff_text: str) -> List[Dict[str, Any]]:
    """
    Parses a git diff or unified patch into structured file chunks.
    """
    files = []
    current_file = None
    lines = diff_text.splitlines()
    
    file_header_re = re.compile(r"^diff --git a/(.*?) b/(.*)$")
    alt_header_re = re.compile(r"^\+\+\+ b/(.*)$")
    
    for line in lines:
        match = file_header_re.match(line)
        if match:
            if current_file:
                files.append(current_file)
            current_file = {
                "old_path": match.group(1),
                "new_path": match.group(2),
                "patch": line + "\n",
                "additions": 0,
                "deletions": 0
            }
            continue
            
        if not current_file:
            alt_match = alt_header_re.match(line)
            if alt_match:
                current_file = {
                    "old_path": alt_match.group(1),
                    "new_path": alt_match.group(1),
                    "patch": line + "\n",
                    "additions": 0,
                    "deletions": 0
                }
                continue
                
        if current_file:
            current_file["patch"] += line + "\n"
            if line.startswith("+") and not line.startswith("+++"):
                current_file["additions"] += 1
            elif line.startswith("-") and not line.startswith("---"):
                current_file["deletions"] += 1
                
    if current_file:
        files.append(current_file)
        
    return files


def call_gemini(api_key: str, model: str, prompt: str, system_prompt: str = "") -> str:
    """
    Calls Google Gemini API via official REST v1beta endpoint.
    Works with gemini-1.5-flash, gemini-1.5-pro, gemini-2.0-flash, etc.
    """
    url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent?key={api_key}"
    headers = {"Content-Type": "application/json"}
    
    contents = []
    if system_prompt:
        payload = {
            "system_instruction": {
                "parts": [{"text": system_prompt}]
            },
            "contents": [
                {"role": "user", "parts": [{"text": prompt}]}
            ],
            "generationConfig": {
                "temperature": 0.2,
                "maxOutputTokens": 4096
            }
        }
    else:
        payload = {
            "contents": [
                {"role": "user", "parts": [{"text": prompt}]}
            ],
            "generationConfig": {
                "temperature": 0.2,
                "maxOutputTokens": 4096
            }
        }
        
    response = requests.post(url, headers=headers, json=payload, timeout=60)
    if response.status_code != 200:
        error_msg = response.text
        try:
            err_json = response.json()
            if "error" in err_json and "message" in err_json["error"]:
                error_msg = err_json["error"]["message"]
        except Exception:
            pass
        raise RuntimeError(f"Gemini API Error ({response.status_code}): {error_msg}")
        
    data = response.json()
    try:
        candidates = data.get("candidates", [])
        if not candidates:
            return "No response generated by model."
        parts = candidates[0].get("content", {}).get("parts", [])
        return "".join([part.get("text", "") for part in parts])
    except Exception as e:
        raise RuntimeError(f"Error parsing Gemini response: {e}\nResponse body: {data}")


def call_openai(api_key: str, model: str, prompt: str, system_prompt: str = "") -> str:
    """
    Calls OpenAI / OpenAI-compatible API (e.g., Groq, OpenRouter, DeepSeek).
    """
    url = "https://api.openai.com/v1/chat/completions"
    headers = {
        "Content-Type": "application/json",
        "Authorization": f"Bearer {api_key}"
    }
    
    messages = []
    if system_prompt:
        messages.append({"role": "system", "content": system_prompt})
    messages.append({"role": "user", "content": prompt})
    
    payload = {
        "model": model,
        "messages": messages,
        "temperature": 0.2,
        "max_tokens": 4096
    }
    
    response = requests.post(url, headers=headers, json=payload, timeout=60)
    if response.status_code != 200:
        error_msg = response.text
        try:
            err_json = response.json()
            if "error" in err_json and "message" in err_json["error"]:
                error_msg = err_json["error"]["message"]
        except Exception:
            pass
        raise RuntimeError(f"OpenAI API Error ({response.status_code}): {error_msg}")
        
    data = response.json()
    return data["choices"][0]["message"]["content"]


