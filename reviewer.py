def generate_review(
    provider: str,
    api_key: str,
    model: str,
    code_or_diff: str,
    context: str = "",
    review_focus: str = "General (Bugs + Security + Performance)"
) -> str:
    """
    Main function to run review across providers.
    """
    prompt = f"""
### Context / PR Description:
{context if context.strip() else "No extra PR description provided by author."}

### Review Focus Area:
{review_focus}

### Code / Diff to Analyze:
```
{code_or_diff}
```

Please execute the detailed code review and PR breakdown following your system guidelines.
"""
    if provider == "Google Gemini":
        return call_gemini(api_key=api_key, model=model, prompt=prompt, system_prompt=REVIEW_SYSTEM_PROMPT)
    elif provider == "OpenAI":
        return call_openai(api_key=api_key, model=model, prompt=prompt, system_prompt=REVIEW_SYSTEM_PROMPT)
    else:
        raise ValueError(f"Unsupported provider: {provider}")


def fetch_github_pr_diff(pr_url: str, github_token: Optional[str] = None) -> Dict[str, Any]:
    """
    Fetches PR details and diff given a GitHub pull request URL.
    Example: https://github.com/owner/repo/pull/123
    """
    match = re.search(r"github\.com/([^/]+)/([^/]+)/pull/(\d+)", pr_url)
    if not match:
        raise ValueError("Invalid GitHub PR URL. Expected format: https://github.com/owner/repo/pull/<number>")
        
    owner, repo, pr_number = match.group(1), match.group(2), match.group(3)
    
    headers = {"Accept": "application/vnd.github.v3+json"}
    diff_headers = {"Accept": "application/vnd.github.v3.diff"}
    if github_token:
        headers["Authorization"] = f"token {github_token}"
        diff_headers["Authorization"] = f"token {github_token}"
        
    # Get PR Metadata
    meta_url = f"https://api.github.com/repos/{owner}/{repo}/pulls/{pr_number}"
    res = requests.get(meta_url, headers=headers, timeout=20)
    if res.status_code != 200:
        raise RuntimeError(f"Failed to fetch PR metadata ({res.status_code}): {res.text}")
    pr_data = res.json()
    
    # Get PR Diff
    diff_res = requests.get(meta_url, headers=diff_headers, timeout=30)
    if diff_res.status_code != 200:
        raise RuntimeError(f"Failed to fetch PR diff ({diff_res.status_code}): {diff_res.text}")
        
    return {
        "title": pr_data.get("title", ""),
        "author": pr_data.get("user", {}).get("login", ""),
        "body": pr_data.get("body", ""),
        "state": pr_data.get("state", ""),
        "additions": pr_data.get("additions", 0),
        "deletions": pr_data.get("deletions", 0),
        "changed_files": pr_data.get("changed_files", 0),
        "diff": diff_res.text
    }
